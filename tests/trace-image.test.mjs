import assert from 'node:assert/strict';
import test from 'node:test';
import { deflateSync } from 'node:zlib';
import { inspectTraceImage } from '../assets/trace-image.mjs';

const byteText = (value) => Buffer.from(value, 'ascii');
const join = (...parts) => Buffer.concat(parts);
const u32 = (value, littleEndian = false) => {
  const bytes = Buffer.alloc(4);
  if (littleEndian) bytes.writeUInt32LE(value);
  else bytes.writeUInt32BE(value);
  return bytes;
};
const pngHeader = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
function pngCrc(data) {
  let accumulator = -1;
  for (const byte of data) {
    accumulator ^= byte;
    for (let i = 0; i < 8; i += 1) accumulator = (accumulator >>> 1) ^ (0xedb88320 & -(accumulator & 1));
  }
  return (~accumulator) >>> 0;
}
const pngChunk = (type, contents = Buffer.alloc(0)) => {
  const data = join(byteText(type), contents);
  return join(u32(contents.length), data, u32(pngCrc(data)));
};
const png = (...metadata) => {
  const header = join(u32(1), u32(1), Buffer.from([8, 0, 0, 0, 0]));
  return join(pngHeader, pngChunk('IHDR', header), ...metadata,
    pngChunk('IDAT', deflateSync(Buffer.from([0, 12]))), pngChunk('IEND'));
};
const box = (type, ...parts) => {
  const contents = join(...parts);
  return join(u32(8 + contents.length), byteText(type), contents);
};
const uuidSuffix = Buffer.from('00110010800000AA00389B71', 'hex');
const description = (type, label) => box('jumd', byteText(type), uuidSuffix, Buffer.of(3), byteText(label + '\0'));
const syntheticStore = (manifestType = 'c2ma') => box('jumb',
  description('c2pa', 'c2pa'), box('jumb', description(manifestType, 'urn:c2pa:test')));
const jfifAppSegment = (marker, body) => {
  const header = Buffer.of(0xff, marker, 0, 0);
  header.writeUInt16BE(body.length + 2, 2);
  return join(header, body);
};
const jpegPart = (number, ...parts) => jfifAppSegment(0xeb,
  join(Buffer.of(0x4a, 0x50, 0x02, 0x11), u32(number), ...parts));
const jpeg = (...metadata) => {
  const scan = jfifAppSegment(0xda, Buffer.of(1, 1, 0, 0, 63, 0));
  return join(Buffer.of(0xff, 0xd8), ...metadata, scan, Buffer.of(2, 0xff, 0, 7, 0xff, 0xd0, 2, 0xff, 0xd9));
};
const riffChunk = (type, contents) => join(byteText(type), u32(contents.length, true),
  contents, Buffer.alloc(contents.length % 2));
const webp = (...items) => {
  const payload = join(byteText('WEBP'), riffChunk('VP8L', Buffer.from([47, 0, 0, 0, 0])), ...items);
  return join(byteText('RIFF'), u32(payload.length, true), payload);
};

test('PNG reports a structured C2PA manifest store with its physical offset', async () => {
  const image = png(pngChunk('caBX', syntheticStore()));
  const result = await inspectTraceImage(image);
  assert.equal(result.format, 'PNG');
  assert.equal(result.findings.length, 1);
  assert.equal(result.findings[0].kind, 'credential');
  assert.match(result.findings[0].location, /PNG caBX.*33/u);
  assert.deepEqual(result.notes, []);
});

test('a PNG carrier requires a C2PA UUID, label, manifest item and valid CRC', async () => {
  const noManifestItem = box('jumb', description('c2pa', 'c2pa'));
  const noC2paLabel = box('jumb', description('c2pa', 'fake'), box('jumb', description('c2ma', 'urn:c2pa:test')));
  const incorrectCrc = pngChunk('caBX', syntheticStore());
  incorrectCrc[incorrectCrc.length - 1] ^= 1;
  for (const badCarrier of [pngChunk('caBX', noManifestItem), pngChunk('caBX', noC2paLabel), incorrectCrc]) {
    const result = await inspectTraceImage(png(badCarrier));
    assert.deepEqual(result.findings, []);
    assert.equal(result.notes.length, 1);
  }
});

test('PNG reports recognized generator names only in named software fields', async () => {
  const image = png(
    pngChunk('tEXt', byteText('Description\0Generated by Midjourney; c2pa and jumb are ordinary text')),
    pngChunk('tEXt', byteText('Software\0Adobe Photoshop')),
    pngChunk('zTXt', join(byteText('Software\0\0'), deflateSync(byteText('OpenAI ChatGPT')))),
  );
  const result = await inspectTraceImage(image);
  assert.deepEqual(result.findings.map(({ kind, value }) => [kind, value]), [['metadata', 'ChatGPT']]);
  assert.deepEqual(result.notes, []);
});

test('PNG compressed metadata exceeding the inspection budget is reported separately', async () => {
  const content = join(byteText('Software\0\0'), deflateSync(Buffer.alloc(520 * 1024, 65)));
  const result = await inspectTraceImage(png(pngChunk('zTXt', content)));
  assert.deepEqual(result.findings, []);
  assert.match(result.notes.join(' '), /容量/u);
});

test('JPEG reconstructs consecutive C2PA APP11 segments with the same instance and box header', async () => {
  const data = syntheticStore('c2um');
  for (const splitAt of [18, 45]) {
    const firstPart = jpegPart(1, data.subarray(0, splitAt));
    const secondPart = jpegPart(2, data.subarray(0, 8), data.subarray(splitAt));
    const result = await inspectTraceImage(jpeg(firstPart, secondPart));
    assert.equal(result.format, 'JPEG');
    assert.equal(result.findings.filter(({ kind }) => kind === 'credential').length, 1);
    assert.deepEqual(result.notes, []);
  }
});

test('JPEG ordinary APP11, comments and incomplete C2PA fragments do not report a credential', async () => {
  const data = syntheticStore();
  const result = await inspectTraceImage(jpeg(
    jfifAppSegment(0xeb, byteText('JPEG 360 ordinary profile')),
    jfifAppSegment(0xfe, byteText('c2pa and jumb')),
    jpegPart(1, data.subarray(0, 45)),
    jfifAppSegment(0xe2, byteText('other metadata')),
    jpegPart(2, data.subarray(0, 8), data.subarray(45)),
  ));
  assert.deepEqual(result.findings, []);
  assert.match(result.notes.join(' '), /分段不完整/u);
});

test('WebP requires an exact C2PA FourCC and respects RIFF chunk bounds and padding', async () => {
  const image = webp(riffChunk('JUNK', byteText('c2pa jumb')), riffChunk('C2PA', syntheticStore('c2md')));
  const result = await inspectTraceImage(image);
  assert.equal(result.format, 'WebP');
  assert.equal(result.findings.filter(({ kind }) => kind === 'credential').length, 1);
  assert.deepEqual(result.notes, []);

  const clean = await inspectTraceImage(webp(riffChunk('c2pa', syntheticStore())));
  assert.deepEqual(clean.findings, []);
  assert.deepEqual(clean.notes, []);
  await assert.rejects(inspectTraceImage(image.subarray(0, -1)), /RIFF 长度/u);
});

test('malformed recognized containers and unsupported formats produce distinct errors', async () => {
  await assert.rejects(inspectTraceImage(png().subarray(0, -1)), /PNG.*结构不完整/u);
  await assert.rejects(inspectTraceImage(jpeg().subarray(0, -1)), /JPEG.*标记段不完整/u);
  await assert.rejects(inspectTraceImage(byteText('Not an image')), /未识别/u);
});
